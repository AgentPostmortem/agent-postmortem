-- Auto-generate case_number on INSERT approval
CREATE SEQUENCE posts_case_number_seq START 1;

CREATE OR REPLACE FUNCTION assign_case_number()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.status = 'approved' AND OLD.status != 'approved' THEN
    NEW.case_number := 'APM-' || LPAD(nextval('posts_case_number_seq')::TEXT, 4, '0');
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

CREATE TRIGGER posts_assign_case_number
  BEFORE UPDATE ON posts
  FOR EACH ROW EXECUTE FUNCTION assign_case_number();

CREATE OR REPLACE FUNCTION update_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

