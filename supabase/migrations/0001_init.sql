-- Maintain vote_score denormalized on posts
CREATE OR REPLACE FUNCTION recalculate_vote_score()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  UPDATE posts
  SET vote_score = (
    SELECT COALESCE(
      SUM(CASE WHEN direction = 'up' THEN 1 ELSE -1 END),
      0
    )
    FROM votes
    WHERE post_id = COALESCE(NEW.post_id, OLD.post_id)
  )
  WHERE id = COALESCE(NEW.post_id, OLD.post_id);
  RETURN NULL;
END;
$$;

CREATE TRIGGER votes_update_score
  AFTER INSERT OR UPDATE OR DELETE ON votes
  FOR EACH ROW EXECUTE FUNCTION recalculate_vote_score();

